function getQuestionText(question?: Question): string {
  if (!question) return '';

  return normalizeDisplayText([
    question.question,
    question.hint ?? '',
    question.explanation,
    ...question.options,
    question.visual?.title ?? '',
    ...(question.visual?.labels ?? []),
    question.visual?.note ?? '',
  ].join(' '));
}

function getConceptSource(concept: ConceptReference, question: Question, selectedAnswerIndex?: number | null): ConceptSource {
  const correctAnswer = normalizeDisplayText(question.options[question.correctAnswer] ?? '');
  const selectedAnswer = selectedAnswerIndex != null ? normalizeDisplayText(question.options[selectedAnswerIndex] ?? '') : '';

  if (concept.match.test(correctAnswer)) return 'correct';
  if (selectedAnswer && selectedAnswerIndex !== question.correctAnswer && concept.match.test(selectedAnswer)) return 'selected';
  if (question.options.some((option) => concept.match.test(normalizeDisplayText(option)))) return 'other-option';

  return 'context';
}

function getConceptReferences(question?: Question, selectedAnswerIndex?: number | null) {
  const text = getQuestionText(question);
  if (!text) return [];

  return concepts
    .filter((concept) => concept.match.test(text))
    .map((concept) => ({
      concept,
      source: question ? getConceptSource(concept, question, selectedAnswerIndex) : 'context',
    }))
    .sort((left, right) => {
      const priority: Record<ConceptSource, number> = {
        correct: 0,
        selected: 1,
        'other-option': 2,
        context: 3,
      };
      return priority[left.source] - priority[right.source];
    })
    .slice(0, 12);
}

export function ConceptReferenceCard({ question, selectedAnswerIndex }: ConceptReferenceCardProps) {
  const matches = getConceptReferences(question, selectedAnswerIndex);
  const [expanded, setExpanded] = useState(false);

  if (matches.length === 0) return null;

  const visible = expanded ? matches : matches.slice(0, 1);
  const hiddenCount = matches.length - visible.length;

  return (
    <section className="concept-reference-card rounded-2xl border border-slate-200 bg-white p-3.5 shadow-sm sm:p-4">
      <div className="flex items-start gap-2.5">
        <div className="rounded-xl bg-violet-100 p-1.5 text-violet-600">
          <SearchCheck className="h-4 w-4" />
        </div>
        <div>
          <p className="text-[9px] font-black uppercase tracking-[0.18em] text-violet-600">Ключові поняття</p>
        </div>
      </div>

      <div className="mt-2.5 grid gap-2">
        {visible.map(({ concept }) => (
          <div key={concept.key} className="rounded-xl border border-violet-100 bg-violet-50/70 p-3">
            <div className="flex flex-wrap items-center gap-2">
              <span className="rounded-lg bg-white px-2 py-1 text-[9px] font-black uppercase tracking-[0.12em] text-violet-700">
                {concept.kind}
              </span>
              <h5 className="text-sm font-black leading-tight text-slate-900">{concept.title}</h5>
            </div>
            <p className="mt-2 text-xs font-semibold leading-relaxed text-slate-700">{concept.description}</p>
            <p className="mt-2 flex gap-1.5 text-[11px] font-bold leading-relaxed text-violet-900">
              <BadgeInfo className="mt-0.5 h-3.5 w-3.5 shrink-0" />
              <span>{concept.memory}</span>
            </p>
          </div>
        ))}
      </div>

      {matches.length > 1 && (
        <button
          type="button"
          onClick={() => setExpanded((current) => !current)}
          className="concept-reference-toggle mt-2.5 flex w-full items-center justify-center gap-1.5 rounded-xl border border-violet-100 bg-white px-3 py-2 text-[10px] font-black uppercase tracking-[0.16em] text-violet-700 transition-colors hover:border-violet-300 hover:bg-violet-50"
        >
          <ChevronDown className={`h-3.5 w-3.5 transition-transform ${expanded ? 'rotate-180' : ''}`} />
          {expanded
            ? 'Згорнути'
            : `Показати ще ${hiddenCount} ${pluralizeConcepts(hiddenCount)}`}
        </button>
      )}
    </section>
  );
}

function pluralizeConcepts(count: number): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return 'поняття';
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'поняття';
  return 'понять';
}
