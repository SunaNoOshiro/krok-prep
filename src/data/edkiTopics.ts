export function applyEdkiTopic<T extends { id: number, topic?: string }>(question: T): T {
  return {
    ...question,
    topic: EDKI_TOPIC_BY_ID[question.id] ?? question.topic,
  };
}

export function sortKrokTopics(topics: string[]): string[] {
  return [...topics].sort((left, right) => {
    const leftIndex = KROK_TOPIC_ORDER.indexOf(left as KrokTopic);
    const rightIndex = KROK_TOPIC_ORDER.indexOf(right as KrokTopic);

    if (leftIndex === -1 && rightIndex === -1) {
      return left.localeCompare(right, 'uk');
    }
    if (leftIndex === -1) return 1;
    if (rightIndex === -1) return -1;
    return leftIndex - rightIndex;
  });
}
